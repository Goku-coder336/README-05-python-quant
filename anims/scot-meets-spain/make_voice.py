"""Generate the dialogue with ElevenLabs, lay it on a timeline, mix to -14 LUFS.

Writes:
  assets/audio/scot-meets-spain/<id>.mp3   one file per line
  assets/audio/scot-meets-spain/dialogue.wav  the mixed track
  anims/scot-meets-spain/timing.js          start/end of every line (used by the animation)
"""
import json, os, subprocess, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "assets/audio/scot-meets-spain"
OUT.mkdir(parents=True, exist_ok=True)
script = json.loads((HERE / "script.json").read_text())

INTRO = 1.4        # title card before the first line
GAP = {"default": 0.45, "l6": 0.75, "l7": 0.9, "l8": 0.15}  # pause before each line
OUTRO = 3.2        # end card after the last line

SETTINGS = {
    "morag": {"stability": 0.30, "similarity_boost": 0.8, "style": 0.55},
    "carmen": {"stability": 0.30, "similarity_boost": 0.8, "style": 0.65},
}


def tts(line):
    path = OUT / f"{line['id']}.mp3"
    if path.exists():
        return path
    body = json.dumps({"text": line["text"], "model_id": "eleven_multilingual_v2",
                       "voice_settings": SETTINGS[line["who"]]})
    voice = script["voices"][line["who"]]
    subprocess.run(["curl", "-sS", "--fail", "-o", str(path), "-X", "POST",
                    f"https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format=mp3_44100_128",
                    "-H", "Content-Type: application/json", "-d", body], check=True)
    return path


def duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "csv=p=0", str(path)], capture_output=True, text=True, check=True)
    return float(r.stdout.strip())


t = INTRO
timing = []
for line in script["lines"]:
    p = tts(line)
    t += GAP.get(line["id"], GAP["default"])
    d = duration(p)
    timing.append({**line, "start": round(t, 3), "end": round(t + d, 3), "file": str(p)})
    t += d
total = round(t + OUTRO, 2)

# Mix: delay every line to its start time, sum, then normalise to -14 LUFS.
inputs, filters = [], []
for i, ln in enumerate(timing):
    inputs += ["-i", ln["file"]]
    ms = int(ln["start"] * 1000)
    filters.append(f"[{i}:a]aresample=48000,adelay={ms}|{ms}[a{i}]")
mix = "".join(f"[a{i}]" for i in range(len(timing)))
filters.append(f"{mix}amix=inputs={len(timing)}:normalize=0,apad=whole_dur={total},"
               f"loudnorm=I=-14:TP=-1.5:LRA=11[out]")
subprocess.run(["ffmpeg", "-y", "-v", "error", *inputs, "-filter_complex", ";".join(filters),
                "-map", "[out]", "-ar", "48000", "-ac", "2", "-t", str(total),
                str(OUT / "dialogue.wav")], check=True)

def envelope(path, fps=30):
    """Loudness per video frame, 0..1, used to open the speaker's mouth (lip sync)."""
    import numpy as np
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", "12000",
                          "-f", "s16le", "-"], capture_output=True, check=True).stdout
    a = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
    n = 12000 // fps
    frames = [float(np.sqrt(np.mean(a[i:i + n] ** 2))) for i in range(0, len(a) - n + 1, n)]
    peak = max(frames) or 1
    return [round(min(1, (f / peak) ** 0.7), 2) for f in frames]


for ln in timing:
    ln["env"] = envelope(ln.pop("file"))
(HERE / "timing.js").write_text(
    "// Generated by make_voice.py - line timings in seconds.\n"
    f"window.SCENE_TIMING = {json.dumps({'total': total, 'lines': timing}, ensure_ascii=False)};\n")
print(json.dumps({"total": total, "lines": [(l['id'], l['start'], l['end']) for l in timing]}))
