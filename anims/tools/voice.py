"""Voice + SFX builder for meme skits.

usage: python3 anims/tools/voice.py anims/<skit>
Reads <skit>/script.json, generates each line (ElevenLabs TTS) and each sound effect
(ElevenLabs sound-generation), lays them on a timeline, mixes to -14 LUFS, and writes
<skit>/timing.js (line + sfx times + per-frame mouth loudness) for the animation.
Audio goes to assets/audio/<skit>/.
"""
import json, subprocess, sys, pathlib
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
SKIT = pathlib.Path(sys.argv[1]).resolve()
NAME = SKIT.name
OUT = ROOT / "assets/audio" / NAME
OUT.mkdir(parents=True, exist_ok=True)
S = json.loads((SKIT / "script.json").read_text())
API = "https://api.elevenlabs.io/v1"


def post(url, body, path):
    if path.exists():
        return path
    subprocess.run(["curl", "-sS", "--fail", "-o", str(path), "-X", "POST", url,
                    "-H", "Content-Type: application/json", "-d", json.dumps(body)], check=True)
    return path


def duration(p):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)],
                       capture_output=True, text=True, check=True)
    return float(r.stdout)


def envelope(p, fps=30):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-ac", "1", "-ar", "12000", "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    a = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
    n = 12000 // fps
    f = [float(np.sqrt(np.mean(a[i:i + n] ** 2))) for i in range(0, len(a) - n + 1, n)]
    pk = max(f) or 1
    return [round(min(1, (v / pk) ** 0.7), 2) for v in f]


# dialogue
t, lines = S.get("intro", 1.0), []
for ln in S["lines"]:
    p = post(f"{API}/text-to-speech/{S['voices'][ln['who']]}?output_format=mp3_44100_128",
             {"text": ln["text"], "model_id": "eleven_multilingual_v2", "voice_settings": S["settings"][ln["who"]]},
             OUT / f"{ln['id']}.mp3")
    t += ln.get("gap", 0.4)
    d = duration(p)
    lines.append({**ln, "start": round(t, 3), "end": round(t + d, 3), "file": str(p)})
    t += d
total = round(t + S.get("outro", 1.5), 2)
by_id = {l["id"]: l for l in lines}

# sound effects
sfx = []
for fx in S.get("sfx", []):
    p = post(f"{API}/sound-generation", {"text": fx["prompt"], "duration_seconds": fx["duration"]}, OUT / f"sfx_{fx['id']}.mp3")
    for at in fx["at"]:
        when = at if isinstance(at, (int, float)) else by_id[at["after"]]["end"] + at["offset"]
        sfx.append({"id": fx["id"], "t": round(when, 3), "gain": fx.get("gain", 1.0), "file": str(p)})
total = max(total, *(s["t"] + 0.5 for s in sfx)) if sfx else total

# mix
clips = [(l["file"], l["start"], 1.0) for l in lines] + [(s["file"], s["t"], s["gain"]) for s in sfx]
args, filt = [], []
for i, (f, start, g) in enumerate(clips):
    args += ["-i", f]
    ms = int(start * 1000)
    filt.append(f"[{i}:a]aresample=48000,aformat=channel_layouts=stereo,volume={g},adelay={ms}|{ms}[a{i}]")
filt.append("".join(f"[a{i}]" for i in range(len(clips))) +
            f"amix=inputs={len(clips)}:normalize=0,apad=whole_dur={total},loudnorm=I=-14:TP=-1.0:LRA=11[out]")
subprocess.run(["ffmpeg", "-y", "-v", "error", *args, "-filter_complex", ";".join(filt), "-map", "[out]",
                "-ar", "48000", "-t", str(total), str(OUT / "mix.wav")], check=True)

for l in lines:
    l["env"] = envelope(l.pop("file"))
for s in sfx:
    s.pop("file")
(SKIT / "timing.js").write_text("// Generated by anims/tools/voice.py\nwindow.SCENE_TIMING = " +
                                json.dumps({"total": round(total, 2), "lines": lines, "sfx": sfx}, ensure_ascii=False) + ";\n")
print("total", round(total, 2))
for l in lines:
    print(l["id"], l["who"], l["start"], l["end"], l["text"])
for s in sfx:
    print("sfx", s["id"], s["t"])
